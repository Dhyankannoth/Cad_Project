/// <reference path="../deno.d.ts" />
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const corsHeaders = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

Deno.serve(async (req) => {
    if (req.method === "OPTIONS") {
        return new Response("ok", { headers: corsHeaders });
    }

    try {
        const supabase = createClient(
            Deno.env.get("SUPABASE_URL"),
            Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")
        );

        const { project_id, format } = await req.json();
        if (!project_id) throw new Error("project_id required");

        // Fetch project
        const { data: project } = await supabase
            .from("projects")
            .select("name, description")
            .eq("id", project_id)
            .single();

        if (!project) throw new Error("Project not found");

        // Fetch all documentation
        const { data: docs } = await supabase
            .from("documentation_sections")
            .select("*, files(file_name, file_path)")
            .eq("project_id", project_id)
            .order("files(file_path)");

        // Fetch metrics
        const { data: metrics } = await supabase
            .from("project_metrics")
            .select("*")
            .eq("project_id", project_id)
            .single();

        let content = "";
        const exportFormat = format || "readme";

        if (exportFormat === "readme") {
            // --- README format ---
            content = `# ${project.name}\n\n`;
            if (project.description) content += `${project.description}\n\n`;

            if (metrics) {
                content += `## Project Stats\n\n`;
                content += `| Metric | Value |\n|--------|-------|\n`;
                content += `| Total Files | ${metrics.total_files} |\n`;
                content += `| Total Functions | ${metrics.total_functions} |\n`;
                content += `| Doc Coverage | ${metrics.doc_coverage_pct}% |\n`;
                content += `| Avg Complexity | ${metrics.avg_complexity} |\n\n`;
            }

            content += `## Modules\n\n`;
            (docs || []).forEach((doc: any) => {
                content += `### ${doc.files?.file_name || "Unknown"}\n`;
                content += `${doc.overview || "No documentation available."}\n\n`;
            });

            content += `\n---\n*Generated by DOCFLOW*\n`;

        } else if (exportFormat === "full") {
            // --- Full documentation ---
            content = `# ${project.name} — Full Documentation\n\n`;
            if (project.description) content += `> ${project.description}\n\n`;

            if (metrics) {
                content += `## Overview\n\n`;
                content += `- **Files:** ${metrics.total_files}\n`;
                content += `- **Functions:** ${metrics.total_functions}\n`;
                content += `- **Documentation Coverage:** ${metrics.doc_coverage_pct}%\n`;
                content += `- **Average Complexity:** ${metrics.avg_complexity}\n\n`;

                if (metrics.orphan_files?.length > 0) {
                    content += `### Orphan Files\nFiles not imported by or importing any other files:\n`;
                    (metrics.orphan_files as string[]).forEach((f: string) => { content += `- \`${f}\`\n`; });
                    content += `\n`;
                }
            }

            content += `---\n\n## File Documentation\n\n`;
            (docs || []).forEach((doc: any) => {
                content += `### ${doc.files?.file_path || "Unknown"}\n\n`;
                content += `**Overview:** ${doc.overview || "N/A"}\n\n`;

                if (doc.architecture_role) {
                    content += `**Architecture Role:** ${doc.architecture_role}\n\n`;
                }

                if (doc.function_docs?.length > 0) {
                    content += `#### Functions\n\n`;
                    (doc.function_docs as any[]).forEach((fn: any) => {
                        content += `- **\`${fn.name}\`** — ${fn.description || "No description"}\n`;
                        if (fn.params) content += `  - Params: ${fn.params}\n`;
                        if (fn.returns) content += `  - Returns: ${fn.returns}\n`;
                    });
                    content += `\n`;
                }

                if (doc.edge_cases?.length > 0) {
                    content += `#### Edge Cases\n`;
                    (doc.edge_cases as string[]).forEach((ec: string) => { content += `- ${ec}\n`; });
                    content += `\n`;
                }

                if (doc.complexity_notes) {
                    content += `#### Complexity\n${doc.complexity_notes}\n\n`;
                }

                content += `---\n\n`;
            });

            content += `*Generated by DOCFLOW — v${docs?.[0]?.version || 1}*\n`;

        } else if (exportFormat === "onboarding") {
            // --- Onboarding guide ---
            content = `# ${project.name} — Onboarding Guide\n\n`;
            content += `Welcome to the ${project.name} codebase! This guide will help you get up to speed.\n\n`;

            if (project.description) content += `## What is this project?\n${project.description}\n\n`;

            if (metrics) {
                content += `## Quick Stats\n`;
                content += `This project has **${metrics.total_files} files** with **${metrics.total_functions} functions**.\n\n`;
            }

            // Key modules
            if (metrics?.central_modules) {
                const centralMods = (metrics.central_modules as any[]).filter((m: any) => m.dependents);
                if (centralMods.length > 0) {
                    content += `## Key Modules to Understand First\n\n`;
                    content += `These are the most imported modules — start here:\n\n`;
                    centralMods.forEach((m: any) => {
                        content += `1. **\`${m.path}\`** (imported by ${m.dependents} files)\n`;
                    });
                    content += `\n`;
                }
            }

            content += `## File-by-File Overview\n\n`;
            (docs || []).forEach((doc: any) => {
                content += `### ${doc.files?.file_name || "Unknown"}\n`;
                content += `${doc.overview || "No overview available."}\n\n`;
            });

            content += `---\n*Generated by DOCFLOW*\n`;
        }

        return new Response(
            JSON.stringify({ success: true, format: exportFormat, content }),
            { headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
    } catch (err: any) {
        return new Response(JSON.stringify({ error: err?.message || "Unknown error" }), {
            status: 500,
            headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
    }
});
